import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(here, "..", "..");
const sourceDir = path.join(here, "src");
const outputFile = path.join(repoRoot, "crates", "lc-core", "assets", "ext-host.mjs");
const sourceFiles = ["jsonrpc.mjs", "workspace.mjs", "storage.mjs", "commands.mjs", "tools.mjs", "host.mjs"];

const IMPORT_PATTERN = /^import\s+[^\n]*;[ \t]*$/gm;
const EXPORT_DECLARATION_PATTERN = /^export\s+(?=(?:async\s+)?function\b|class\b|const\b|let\b|var\b)/gm;
const EXPORT_LIST_PATTERN = /^export\s*\{[^}\n]*\};?[ \t]*$/gm;

const banner = `// Generated by sidecars/ext-host/build.mjs from sidecars/ext-host/src/.
// Do not edit this file by hand. Rebuild with: node sidecars/ext-host/build.mjs
`;

const imports = new Set();
let body = "";

for (const name of sourceFiles) {
  const file = path.join(sourceDir, name);
  let source = fs.readFileSync(file, "utf8");

  for (const line of source.match(IMPORT_PATTERN) ?? []) {
    if (/from\s+["']node:/.test(line)) imports.add(line.trim());
  }
  source = source.replace(IMPORT_PATTERN, "");
  source = source.replace(EXPORT_DECLARATION_PATTERN, "");
  source = source.replace(EXPORT_LIST_PATTERN, "");
  source = source.trim();

  if (/^export\b/m.test(source)) throw new Error(`${name}: unhandled export statement`);
  if (/^import\b/m.test(source)) throw new Error(`${name}: unhandled import statement`);
  if (/from\s+["']\.\//.test(source)) throw new Error(`${name}: local import was not stripped`);

  body += `\n// ---- ${name} ----\n\n${source}\n`;
}

const bundle = `${banner}\n${[...imports].sort().join("\n")}\n${body}`;
const current = fs.existsSync(outputFile) ? fs.readFileSync(outputFile, "utf8") : null;

if (process.argv.includes("--check")) {
  if (current !== bundle) {
    console.error(
      `${path.relative(repoRoot, outputFile)} is out of date; run "node sidecars/ext-host/build.mjs"`
    );
    process.exit(1);
  }
  console.log(`${path.relative(repoRoot, outputFile)} is up to date`);
} else {
  fs.mkdirSync(path.dirname(outputFile), { recursive: true });
  fs.writeFileSync(outputFile, bundle, "utf8");
  console.log(`wrote ${path.relative(repoRoot, outputFile)} (${Buffer.byteLength(bundle)} bytes)`);
}
